// Builds js/module-deps.js: every module each lazily loaded part of the app needs, so app.js can request them all
// at once instead of one import chain after another (each step costs a round trip on a phone).
// Run: node scripts/module-deps.mjs        (check.mjs fails if the committed file is out of date)
import { readFileSync, writeFileSync } from 'node:fs';

const ENTRIES = { phrases: ['data.js', 'furigana.js', 'ways.js'], study: ['study.js'], speaking: ['speaking.js'], jlpt: ['jlpt.js'], exam: ['exam.js'], strokes: ['strokes.js'], path: ['path.js'], search: ['search.js'], book: ['book.js'], board: ['board.js'] };
const LOADED_FIRST = new Set(['app.js', 'units-index.js', 'core.js', 'clips.js', 'speech.js']); // already on the home screen

const importsOf = f => [...readFileSync(new URL(`../js/${f}`, import.meta.url), 'utf8')
  .matchAll(/^import\s[^;]*?from\s+'\.\/([a-z0-9-]+\.js)'/gm)].map(m => m[1]);

export function buildDeps() {
  const out = {};
  for (const [name, roots] of Object.entries(ENTRIES)) {
    const seen = new Set(), stack = [...roots];
    while (stack.length) { const f = stack.pop(); if (seen.has(f)) continue; seen.add(f); stack.push(...importsOf(f)); }
    out[name] = [...seen].filter(f => !LOADED_FIRST.has(f)).sort();
  }
  return `// Generated by scripts/module-deps.mjs from the import lines. Do not edit by hand; run the script instead.
export const DEPS = ${JSON.stringify(out, null, 2).replace(/"(\w+)":/g, '$1:')};
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(new URL('../js/module-deps.js', import.meta.url), buildDeps());
  console.log('js/module-deps.js written');
}
