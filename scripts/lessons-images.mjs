export const EXTRA = []; // maps, menus and scenes are appended below as units are added

export function run(list) {
  for (const [file, page, x, y, w, h, width = 360, isGray = false] of list) {
    const out = `img/lessons/${file}.jpg`;
    mkdirSync(out.replace(/\/[^/]+$/, ''), { recursive: true });
    execFileSync(tool, ['crop', pdf, String(page), ...[x, y, w, h].map(v => v.toFixed(4)), out, String(width), isGray ? '0.6' : '0.7', isGray ? '1' : '0']);
  }
}

if (import.meta.url === `file://${process.argv[1]}`) {
  if (!pdf || !tool) { console.error('usage: node scripts/lessons-images.mjs <source.pdf> <lsimg>'); process.exit(1); }
  const { SCENES } = await import('./lessons-scenes.mjs').catch(() => ({ SCENES: [] }));
  const all = [...CROPS, ...SCENES];
  run(all);
  const total = all.reduce((n, c) => n + statSync(`img/lessons/${c[0]}.jpg`).size, 0);
  console.log(`${all.length} pictures, ${(total / 1024).toFixed(0)} KB`);
  writeSizes();
}

// JPEG width and height, from the frame header (SOF0–SOF3).
function jpegSize(buf) {
  for (let i = 2; i < buf.length;) {
    if (buf[i] !== 0xFF) { i++; continue; }
    const m = buf[i + 1], len = buf.readUInt16BE(i + 2);
    if (m >= 0xC0 && m <= 0xC3) return [buf.readUInt16BE(i + 7), buf.readUInt16BE(i + 5)];
    i += 2 + len;
  }
  throw new Error('not a JPEG');
}

// js/lessons-pics.js: every picture's size, so the app can reserve its space before it loads.
export function picSizes() {
  const out = {};
  const walk = dir => readdirSync(dir, { withFileTypes: true }).forEach(d => d.isDirectory() ? walk(`${dir}/${d.name}`)
    : d.name.endsWith('.jpg') && (out[`${dir}/${d.name}`.slice('img/lessons/'.length, -4)] = jpegSize(readFileSync(`${dir}/${d.name}`))));
  walk('img/lessons');
  const keys = Object.keys(out).sort();
  return `// Generated by scripts/lessons-images.mjs: size [width, height] of each Lessons tab picture in img/lessons/.
export const PIC_SIZE = {
${keys.map(k => `  '${k}': [${out[k].join(', ')}],`).join('\n')}
};
`;
}
function writeSizes() { writeFileSync('js/lessons-pics.js', picSizes()); }
