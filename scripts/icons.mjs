// Builds js/icons.js: the interface icons (tabs, header, mode buttons, hub cards, board) as inline SVG, taken from
// Lucide (lucide.dev, ISC licence, credited in Settings → Credits). Inline SVG instead of emoji because emoji look
// different on every phone (and some older Androids show a box), ignore the colour theme, and several were hard to
// read (🪜 for the JLPT path). The icons draw in the text colour, so they follow light/dark and the red active tab.
// Emoji stay where they are content: vocab and food pictures, unit icons, 🎉 🏆.
//
// Regenerate (only after changing NAMES):
//   npm pack lucide-static@0.460.0 && tar -xzf lucide-static-0.460.0.tgz && node scripts/icons.mjs package/icons
import { readFileSync, writeFileSync } from 'node:fs';

// App name → Lucide icon. The app name says what the icon means here, so a swap later touches only this list.
export const NAMES = {
  phrases: 'message-circle',       // Phrases tab: everyday sentences
  'path-jlpt': 'map',              // N5·N4 path: the route through the course, level by level
  'path-talk': 'messages-square',  // Fluent path: conversation
  speak: 'mic',                    // Speak tab, Speak mode
  study: 'book-open',              // Study tab
  jlpt: 'graduation-cap',          // JLPT tab: the exam
  book: 'book-marked',             // Book tab: the textbook
  board: 'users',                  // 👥 board (header)
  search: 'search',
  settings: 'settings',
  learn: 'layers',                 // Learn mode: a stack of flashcards
  roleplay: 'messages-square',
  home: 'house',
  work: 'briefcase',               // Life & work words
  verbs: 'zap',                    // verbs = actions
  grammar: 'notebook-text',        // grammar points
  strokes: 'pen-line',             // stroke order
  shadow: 'repeat',                // shadowing: listen and repeat
  questions: 'message-circle-question',
  builder: 'puzzle',
  intro: 'circle-user-round',      // self-introduction
  sounds: 'audio-lines',           // pronunciation
  reading: 'book-open',
  listening: 'headphones',
  vocab: 'image',                  // words with pictures
  done: 'circle-check',            // board: done
  now: 'map-pin',                  // board: you are here
  left: 'hourglass',               // board: still to do
};

export function buildIcons(dir) {
  const inner = name => {
    const svg = readFileSync(`${dir}/${name}.svg`, 'utf8');
    const body = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>'));
    // One line, no self-closing spaces: compact and identical however the source file is formatted.
    return body.replace(/\s*\n\s*/g, '').replace(/\s+\/>/g, '/>').trim();
  };
  const rows = Object.entries(NAMES).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(inner(v))},`).join('\n');
  return `// Generated by scripts/icons.mjs from Lucide 0.460.0 (https://lucide.dev, ISC licence: Copyright (c) Lucide
// Contributors 2022, portions Copyright (c) Cole Bemis 2013-2022 as part of Feather, MIT). Do not edit by hand.
export const ICONS = {
${rows}
};

// An icon as inline SVG markup. Decorative (aria-hidden): every icon sits next to a text label or inside a
// control with an aria-label, so screen readers read the words, not the picture.
export const icon = name => \`<svg class="ic" viewBox="0 0 24 24" aria-hidden="true" focusable="false">\${ICONS[name] || ''}</svg>\`;
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const dir = process.argv[2];
  if (!dir) { console.error('Usage: node scripts/icons.mjs <lucide-static>/icons'); process.exit(1); }
  writeFileSync(new URL('../js/icons.js', import.meta.url), buildIcons(dir));
  console.log('js/icons.js written');
}
