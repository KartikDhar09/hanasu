// Builds js/units-index.js: the tracks and unit list the home screen shows, so the first load doesn't need
// the full phrase data (js/data.js, ~40 KB compressed), which then loads right after the first paint.
// Run: node scripts/units-index.mjs        (check.mjs fails if the committed file is out of date)
import { writeFileSync } from 'node:fs';

export async function buildIndex() {
  const { TRACKS, UNITS, CARDS } = await import('../js/data.js');
  const units = UNITS.map(u => ({ id: u.id, track: u.track, title: u.title, jp: u.jp, hi: u.hi, n: CARDS.filter(c => c.unit === u.id).length }));
  return `// Generated by scripts/units-index.mjs from js/data.js. Do not edit by hand; run the script instead.
export const TRACKS = ${JSON.stringify(TRACKS)};
export const UNIT_INDEX = ${JSON.stringify(units).replace(/\},\{/g, '},\n  {').replace('[{', '[\n  {').replace('}]', '},\n]')};
export const PHRASE_COUNT = ${CARDS.length};
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(new URL('../js/units-index.js', import.meta.url), await buildIndex());
  console.log('js/units-index.js written');
}
