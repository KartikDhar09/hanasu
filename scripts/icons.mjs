export function buildIcons(dir) {
  const inner = name => {
    const svg = readFileSync(`${dir}/${name}.svg`, 'utf8');
    const body = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>'));
    // One line, no self-closing spaces: compact and identical however the source file is formatted.
    return body.replace(/\s*\n\s*/g, '').replace(/\s+\/>/g, '/>').trim();
  };
  const rows = Object.entries(NAMES).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(inner(v))},`).join('\n');
  return `// Generated by scripts/icons.mjs from Lucide 0.460.0 (https://lucide.dev, ISC licence: Copyright (c) Lucide
// Contributors 2022, portions Copyright (c) Cole Bemis 2013-2022 as part of Feather, MIT). Do not edit by hand.
export const ICONS = {
${rows}
};

// An icon as inline SVG markup. Decorative (aria-hidden): every icon sits next to a text label or inside a
// control with an aria-label, so screen readers read the words, not the picture.
export const icon = name => \`<svg class="ic" viewBox="0 0 24 24" aria-hidden="true" focusable="false">\${ICONS[name] || ''}</svg>\`;
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const dir = process.argv[2];
  if (!dir) { console.error('Usage: node scripts/icons.mjs <lucide-static>/icons'); process.exit(1); }
  writeFileSync(new URL('../js/icons.js', import.meta.url), buildIcons(dir));
  console.log('js/icons.js written');
}
