// Builds js/path-summary.js: each path level's title and how much it covers, so the 👥 board can say what is done,
// current and left in every tab from a person's two level numbers, without loading the full path files (~94 KB with
// all their test questions). The paths split the whole course: every grammar point, kanji group, vocab topic and
// particle sits in exactly one N5·N4 level, and every Phrases unit and Speak Q&A in exactly one Fluent level.
// Run: node scripts/path-summary.mjs        (check.mjs fails if the committed file is out of date)
import { writeFileSync } from 'node:fs';

export async function buildSummary() {
  const { PATH_JLPT } = await import('../js/path-jlpt.js');
  const { PATH_TALK } = await import('../js/path-talk.js');
  const n = a => (a || []).length;
  // One line per level: [title, ...counts], counts in the order of that path's kinds.
  const jlpt = PATH_JLPT.map(l => [l.title, n(l.study.grammar), n(l.study.kanji), n(l.study.vocab), n(l.study.particles)]);
  const talk = PATH_TALK.map(l => [l.title, n(l.study.units), n(l.study.qa)]);
  const rows = a => a.map(r => '      ' + JSON.stringify(r)).join(',\n');
  return `// Generated by scripts/path-summary.mjs from js/path-jlpt.js and js/path-talk.js. Do not edit by hand; run the script.
// Per level: [title, ...how many of each kind it teaches]. The kinds name the counts, singular and plural.
export const PATH_SUMMARY = {
  jlpt: {
    kinds: [['grammar point', 'grammar points'], ['kanji group', 'kanji groups'], ['vocab topic', 'vocab topics'], ['particle', 'particles']],
    levels: [
${rows(jlpt)},
    ],
  },
  talk: {
    kinds: [['Phrases unit', 'Phrases units'], ['Speak Q&A', 'Speak Q&As']],
    levels: [
${rows(talk)},
    ],
  },
};
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(new URL('../js/path-summary.js', import.meta.url), await buildSummary());
  console.log('js/path-summary.js written');
}
